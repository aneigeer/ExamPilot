-- ---------- 自检 ----------
SELECT COUNT(*) AS 考研类别数 FROM `exam_category` WHERE `code` = 'POSTGRAD' AND `is_deleted` = 0;
SELECT COUNT(*) AS 考研科目数 FROM `subject` WHERE `exam_category_id` = 7 AND `is_deleted` = 0;
SELECT COUNT(*) AS 考研题目数 FROM `question` q JOIN `subject` s ON s.id = q.subject_id
WHERE s.exam_category_id = 7;
