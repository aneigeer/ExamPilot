-- ============================================================
-- 品类扩展：新增「考研」考试类别与科目骨架（**只占位，不灌题库**）
--
-- 为什么现在就要补：
--   用户目标里的「多品类」包含考研，而考试类别此前只有
--   校内课程 / 四级 / 六级 / 计算机二级 / 信息与计算科学 / 国考。
--   品类是**表结构层面的东西**，越晚加，后面越多的关联数据（知识点、
--   题目、语料、画像）都要跟着迁移，所以先把骨架立起来。
--
-- 为什么只占位不灌题：
--   考研题目的入库依赖「解析器重做 + OCR 建题接入」（见《软件状态总纲》§8.2），
--   现在硬灌会重复国考真题踩过的坑（水印、页脚、公式/表格丢失、
--   不可作答题混入公共题库）。先占位，等抽取链路可靠了再灌。
--
-- 幂等：INSERT IGNORE + 显式 ID，重复执行不产生重复数据。
--
-- 执行：mysql -uroot -p exam_prep < sql/migration-postgrad-category.sql
-- ============================================================
USE exam_prep;

