from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "training" / "data" / "eval_refusal_hard.jsonl"
HOLDOUT = ROOT / "training" / "data" / "eval_holdout.jsonl"

_holdout = [json.loads(l) for l in HOLDOUT.read_text(encoding="utf-8").splitlines() if l.strip()]
SYSTEM = next(r for r in _holdout if r.get("kind") == "refusal")["messages"][0]["content"]
REFUSAL = "未找到相关资料"


def row(qid: int, scene: str, stem: str, docs: list[tuple[str, str]], note: str, **extra) -> dict:
    material = "\n".join(f"[{i}] {title}：{text}" for i, (title, text) in enumerate(docs, 1))
    user = f"【资料】\n{material}\n\n【问题】\n{stem}"
    meta = {
        "qid": int(qid),
        "scene": scene,
        "source": f"题库原题 qid={qid}；资料为构造/改写文本，未使用训练集原文",
        "material_source": "constructed_for_eval",
        "note": note,
    }
    meta.update(extra)
    return {
        "messages": [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": user},
            {"role": "assistant", "content": REFUSAL},
        ],
        "kind": "refusal",
        "meta": meta,
    }


